const KIND_LABEL: Record<ProductImageKind, string> = {
  front: "front view",
  back: "back view",
  "close-up": "close-up of the beads",
  detail: "detail",
  lifestyle: "worn on the wrist",
  packaging: "in its Hi 5 gift pouch",
  "size-reference": "next to a ruler for size",
};

const ALL_KINDS: ProductImageKind[] = [
  "front",
  "back",
  "close-up",
  "detail",
  "lifestyle",
  "packaging",
  "size-reference",
];

const PREVIEW_KINDS: ProductImageKind[] = ["front", "back", "close-up", "packaging"];

function gallery(slug: string, name: string, kinds: ProductImageKind[] = ALL_KINDS): ProductImage[] {
  return kinds.map((kind) => ({
    src: `/products/${slug}/${kind}.svg`,
    alt: `${name} – ${KIND_LABEL[kind]} (illustration)`,
    kind,
    width: 1200,
    height: 1200,
  }));
}

